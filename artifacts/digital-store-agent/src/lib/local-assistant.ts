export type CloudSpeechProvider = 'elevenlabs' | 'azure';

export type CloudSpeechRequest = {
  provider: CloudSpeechProvider;
  text: string;
  locale: 'ar-SA' | 'ar-EG' | 'en-US' | 'en-GB' | 'fr-FR' | 'fr-CA';
  voiceId?: string;
};

export type CloudSpeechAdapter = (request: CloudSpeechRequest) => Promise<Blob>;

export function generateLocalAssistantReply(message: string): string {
  const normalized = message
    .normalize('NFKC')
    .toLocaleLowerCase('ar')
    .replace(/[\u064B-\u065F\u0670]/gu, '')
    .replace(/[أإآ]/gu, 'ا')
    .replace(/ى/gu, 'ي');

  if (/ما اسمك|اسمك ايه|من انت|من تكون|مين انت|عرفيني بنفسك/.test(normalized)) {
    return 'أنا روبي، وكيلتك الذكية لمساعدتك في إدارة متجرك الرقمي وتطويره.';
  }

  if (/كيف حالك|كيفك|كيف امورك|كيف الحال/.test(normalized)) {
    return 'أنا بخير، شكراً لسؤالك. كيف يمكنني مساعدتك في إدارة متجرك؟';
  }

  if (/السلام عليكم|مرحبا|اهلا|هلا|صباح الخير|مساء الخير/.test(normalized)) {
    return 'وعليكم السلام، أهلاً بك. أنا روبي، وكيلتك الذكية لإدارة متجرك الرقمي. كيف أستطيع مساعدتك؟';
  }

  if (/binance|باينانس|بينانس|واتساب|whatsapp|ربط|تكامل|اعداد|تفعيل/.test(normalized)) {
    return 'يمكنني مساعدتك في إعداد التكامل. تحقّق من حالة الخدمة في الإعدادات، وأضف بياناتها السرية إلى الخادم فقط. لا تشارك مفاتيح API أو رموز التحقق في المحادثة.';
  }

  if (/مبيعات|ايراد|ارباح|مدفوعات|ماليه|تحويل|صرف/.test(normalized)) {
    return 'لمراجعة المبيعات، افتح صفحة المبيعات. وللاطلاع على الإيرادات والتحويلات، افتح صفحة المالية. ستظهر البيانات التي توفرها الخدمات المتصلة فقط.';
  }

  if (/منتج|منتجات|كتالوج|سعر|خطة/.test(normalized)) {
    return 'يمكنك إدارة المنتجات الرقمية وخطط الأسعار من صفحة المنتجات، ثم إنشاء رابط دفع. أخبرني بنوع المنتج وجمهوره لأساعدك في إعداد وصف مناسب.';
  }

  if (/تصميم|تصاميم|هويه|الوان|خطوط|واجهه|صوره|غلاف/.test(normalized)) {
    return 'يسعدني مساعدتك في تطوير فكرة التصميم. ما نوع المنتج؟ ومن جمهوره المستهدف؟ وما الانطباع الذي ترغب في أن يتركه؟';
  }

  if (/متجر|ادير|اداره|كيف ابدا/.test(normalized)) {
    return 'ابدأ بمراجعة لوحة المعلومات، ثم أضف منتجاتك وروابط الدفع، وتابع المبيعات والشؤون المالية من الصفحات المخصصة. ما الجانب الذي ترغب في إعداده أولاً؟';
  }

  return 'أنا هنا لمساعدتك في إدارة متجرك الرقمي. أخبرني بما ترغب في إنجازه، وسأقترح عليك الخطوات المناسبة.';
}